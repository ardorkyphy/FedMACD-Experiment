def _cell_means(rows, nan_to_zero=False):
    """(dataset, scenario) -> mean F1 / nSHD / SHD over the folds of that cell."""
    acc = {}
    for row in rows:
        slot = acc.setdefault((str(row['dataset']), str(row['scenario'])), {})
        for metric in ('f1', 'nshd', 'shd'):
            value = C.fnum(row.get(metric))
            if value is None:
                if not nan_to_zero:
                    continue
                value = 0.0
            slot.setdefault(metric, []).append(value)
    return dict((key, dict((m, st.fmean(v)) for m, v in slot.items() if v))
                for key, slot in acc.items())


def _avg_rank(values, ascending):
    """Competition ranking; tied values share the mean of the ranks they span."""
    order = sorted(range(len(values)), key=lambda i: values[i], reverse=not ascending)
    ranks = [0.0] * len(values)
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and abs(values[order[j + 1]] - values[order[i]]) < 1e-12:
            j += 1
        for t in range(i, j + 1):
            ranks[order[t]] = (i + 1 + j + 1) / 2.0
        i = j + 1
    return ranks


def _cell_rank(names, f1, nshd, shd):
    """Composite rank: mean of the three per-metric ranks, re-ranked, ties averaged."""
    parts = [(_avg_rank(f1, False)[k] + _avg_rank(nshd, True)[k] + _avg_rank(shd, True)[k]) / 3.0
             for k in range(len(names))]
    final = _avg_rank(parts, True)
    return dict((names[k], final[k]) for k in range(len(names)))


def tab1_rank():
    """Tab. 1: mean composite rank of every domain-matched federated method.

    A cell is the mean over the five datasets of its domain; the overall column
    is the mean over the four (domain, scenario) cells a method takes part in.
    Baseline rows are listed on the qwen pool (the caption says so).
    """
    data = {}
    for backbone in C.BACKBONE_ORDER:
        data[backbone] = _cell_means(C.main_rows(backbone))
    for name in RANK_METHODS[3:]:
        path, alg, to_zero = C.BASELINES[name]
        data[name] = _cell_means(C.load_csv(path, alg), to_zero)

    cells = dict((m, {}) for m in RANK_METHODS)
    for domain, datasets, pool in RANK_DOMAINS:
        for scenario in SCENARIOS:
            for backbone in C.BACKBONE_ORDER:
                names = [backbone] + pool
                kept = dict((m, []) for m in names)
                for ds in datasets:
                    key = (ds, scenario)
                    if any(key not in data[m] or len(data[m][key]) < 3 for m in names):
                        continue
                    ranks = _cell_rank(names,
                                       [data[m][key]['f1'] for m in names],
                                       [data[m][key]['nshd'] for m in names],
                                       [data[m][key]['shd'] for m in names])
                    for m in names:
                        kept[m].append(ranks[m])
                cells[RANK_METHODS[C.BACKBONE_ORDER.index(backbone)]][(domain, scenario)] = (
                    st.fmean(kept[backbone]) if kept[backbone] else None)
                if backbone == C.BACKBONE_ORDER[0]:
                    for m in pool:
                        cells[m][(domain, scenario)] = st.fmean(kept[m]) if kept[m] else None

    for m in RANK_METHODS:
        present = [cells[m][c] for c in RANK_COLUMNS[:-1] if cells[m].get(c) is not None]
        cells[m]['overall'] = st.fmean(present) if present else None
        for col, want in zip(RANK_COLUMNS, ANCHOR_RANK[m]):
            got = cells[m].get(col)
            if want is None:
                assert got is None, ('rank: unexpected value', m, col, got)
            else:
                assert got is not None and abs(got - want) < 5e-3, ('rank', m, col, got, want)

    best = dict((c, min(cells[m][c] for m in RANK_METHODS if cells[m].get(c) is not None))
                for c in RANK_COLUMNS)
    rows = []
    for m in RANK_METHODS:
        if m == 'FedPC':
            rows.append(r'\midrule')
        parts = []
        for c in RANK_COLUMNS:
            value = cells[m].get(c)
            if value is None:
                parts.append('---')
            elif abs(value - best[c]) < 1e-9:
                parts.append(r'\textbf{%s}' % rank2(value))
            else:
                parts.append(rank2(value))
        rows.append('%s & %s' % (m, ' & '.join(parts)))
    return rows


def tab2():
    rows, seen = [], {}
    for scen, label in (('homogeneous', 'homogeneous'),
                        ('heterogeneous', 'heterogeneous'),
                        (None, 'both pooled')):
        if label != 'homogeneous':
            rows.append(r'\midrule')
        for metric, nd in (('D_acc', 3), ('F1', 3), ('SHD', 2)):
            cells = [C.ablation_pooled(s, metric, scen) for s in C.ABL_SETTINGS]
            anchor = ANCHOR1[(label, metric)]
            tol = TOL[metric]
            for k, (value, sd) in enumerate(cells):
                assert abs(value - anchor[2 * k]) < tol, (label, metric, k, value, anchor[2 * k])
                assert abs(sd - anchor[2 * k + 1]) < tol, (label, metric, k, sd, anchor[2 * k + 1])
            full, no_local, no_debate, neither = [cell[0] for cell in cells]
            # Two-factor coefficients defined in the manuscript, also for SHD.
            dc = (full + no_debate - no_local - neither) / 4.0
            dd = (full + no_local - no_debate - neither) / 4.0
            seen[(label, metric)] = (cells, dc, dd)
            dfmt = '$%+.4f$'
            rows.append(' & '.join([
                label,
                metric if metric != 'D_acc' else '$D_{acc}$',
                C.fmt_pm(cells[0][0], cells[0][1], nd),
                C.fmt_pm(cells[1][0], cells[1][1], nd),
                C.fmt_pm(cells[2][0], cells[2][1], nd),
                C.fmt_pm(cells[3][0], cells[3][1], nd),
                dfmt % dc,
                dfmt % dd,
            ]))
    return rows, seen


def tab3():
    """Tab. 3: directed F1 and SHD at 0 / 1 / 2 / 3 debate rounds.

    Tokens are printed next to F1 / SHD (plain means over the three seeds of the
    cell); the accuracy--cost trade-off proper lives in Fig. 5, which is taken
    from the three backbones of the main experiment.
    """
    rows = []
    for ds in ROUND_DATASETS:
        for scen in SCENARIOS:
            cells = []
            for rnd in (0, 1, 2, 3):
                if rnd == 0:
                    sub = C.pick(C.ablation_rows(), variant='no_debate', dataset=ds, scenario=scen)
                elif rnd == 1:
                    sub = C.pick(C.bonus_rows('rounds1'), dataset=ds, scenario=scen)
                elif rnd == 2:
                    sub = C.pick(C.main_rows(), dataset=ds, scenario=scen)
                else:
                    sub = C.pick(C.bonus_rows('rounds3'), dataset=ds, scenario=scen)
                assert len(sub) == 3, (ds, scen, rnd, len(sub))
                f1 = st.fmean([C.fnum(r['f1']) for r in sub])
                shd = st.fmean([C.fnum(r['shd']) for r in sub])
                tok = st.fmean([C.fnum(r['llm_total_tokens']) for r in sub]) / 1000.0
                cells.append((f1, shd, tok))
            for k, (f1, shd, tok) in enumerate(cells):
                a = ANCHOR2[(ds, scen)][k]
                assert abs(f1 - a[0]) < 5e-4, (ds, scen, k, f1, a[0])
                assert abs(shd - a[1]) < 5e-3, (ds, scen, k, shd, a[1])
                assert round(tok) == a[2], (ds, scen, k, tok, a[2])
            best = max(range(len(cells)), key=lambda k: cells[k][0])
            parts = []
            for k, (f1, shd, tok) in enumerate(cells):
                txt = '%.3f' % f1
                parts.append('\\textbf{%s}' % txt if k == best else txt)
                parts.append('%.2f' % shd)
                parts.append('%d' % round(tok))
            rows.append('%-13s & %-13s & %s' % (esc(ds), scen, ' & '.join(parts)))
    return rows


def _fold_rows(setting, dataset, scenario):
    rows = (C.pick(C.main_rows(), dataset=dataset, scenario=scenario)
            if setting == 'Ours' else
            C.pick(C.ablation_rows(), variant=setting, dataset=dataset, scenario=scenario))
    led = (C.pick(C.edge_rows(), variant=setting, dataset=dataset, scenario=scenario))
    assert len(rows) == 3 and len(led) == 3, (setting, dataset, scenario, len(rows), len(led))
    out = []
    for seed in (0, 1, 2):
        r = C.pick(rows, seed=seed)[0]
        l = C.pick(led, seed=seed)[0]
        assert abs(C.fnum(r['f1']) - C.micro_f1([r])) < 1e-9, ('f1 mismatch', setting, dataset, scenario, seed)
        out.append((l['D_correct'] / l['D_den'], C.fnum(r['f1']), C.fnum(r['shd'])))
    return out, C.d_acc(led)


