def esc(name):
    return name.replace('_', r'\_')


def num(value, nd=3):
    """Integer-valued numbers print without decimals, others with ``nd``."""
    if abs(value - round(value)) < 1e-9:
        return '%d' % round(value)
    return '%.*f' % (nd, value)


def rank2(value):
    """Rank cells print with two decimals; an exact half rounds up (1.625 -> 1.63)."""
    return str(decimal.Decimal(repr(round(value, 6))).quantize(
        decimal.Decimal('0.01'), rounding=decimal.ROUND_HALF_UP))


def write(fname, lines):
    path = os.path.join(C.TABLE_DIR, fname)
    stamp = datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    head = ['% generated by scripts/paper_figures/make_tables.py on ' + stamp,
            '% do not edit by hand -- rerun the script instead']
    body = [l + r' \\' if '&' in l else l for l in lines]
    with io.open(path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(head + body) + '\n')
    print('wrote %s (%d lines)' % (path, len(lines)))


